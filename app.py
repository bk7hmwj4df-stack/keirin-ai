import os
import streamlit as st
from openai import OpenAI

# =========================
# 基本設定
# =========================

st.set_page_config(
    page_title="競輪AI ガチ分析版",
    page_icon="🚴",
    layout="wide"
)

st.title("🚴 競輪AI ガチ分析版")

st.caption(
    "AIが過去成績・近況・脚質・決まり手・ライン・展開を調査し、"
    "考え抜いた三連単フォーメーションを作成します。"
)

# =========================
# APIキー取得
# =========================

api_key = None

try:
    api_key = st.secrets["OPENAI_API_KEY"]
except Exception:
    pass

if not api_key:
    api_key = os.getenv("OPENAI_API_KEY")

if not api_key:
    st.error(
        "OPENAI_API_KEY が設定されていません。"
    )
    st.stop()

client = OpenAI(
    api_key=api_key
)

# =========================
# AIへの指示
# =========================

SYSTEM_PROMPT = """
あなたは競輪の三連単予想を専門にする高度な競輪分析AIです。

目的は単純な競走得点順や人気順の予想ではありません。

ユーザーから与えられた情報と、Web検索で確認できる情報を可能な限り分析し、
過去成績、近況、走り、脚質、決まり手、ライン、展開を総合判断して、
実際に起こる可能性が高い三連単フォーメーションを作成してください。

【最重要ルール】

まずオッズを見ない状態でデータと展開から本命評価を決める。
オッズがある場合は最後の買い目調整にだけ使用する。
オッズだけで本命評価を変更してはいけない。

【必ず分析する項目】

可能な限り以下を確認する。

・直近成績
・過去の着順
・近況の上昇下降
・競走得点
・勝率
・連対率
・3連対率
・S
・H
・B
・決まり手
・逃げ
・捲り
・差し
・マーク
・脚質
・先行力
・捲り力
・番手戦の強さ
・追込み能力
・ライン構成
・並び予想
・ラインの長さ
・主導権争い
・バンク特性
・過去対戦
・開催レベル

データが確認できない場合は、
存在しない情報を作ってはいけない。

【分析手順】

1. 全選手を評価する。

2. 各選手の過去成績と直近の調子を分析する。

3. ライン構成を確認する。

4. レース展開を最低3パターン考える。

パターンA：
本命ラインが主導権を取る展開。

パターンB：
別線の自力選手が捲る展開。

パターンC：
先行争いから番手選手や追込み選手が浮上する展開。

5. 1着、2着、3着を別々に評価する。

単純な能力順に
1着、2着、3着を並べてはいけない。

各選手について、

・1着になる可能性
・2着になる可能性
・3着になる可能性
・展開次第で浮上する可能性

を個別に考える。

【フォーメーション作成ルール】

明確な1強でない限り、
1着候補は原則2人程度にする。

1着と2着を固定した買い方を繰り返さない。

例えば、

1-2-345
1-2-367

のような、
1着と2着が完全に固定された不自然な買い方は禁止。

展開によって、

1が1着で2が2着

2が1着で1が2着

別の選手が2着に浮上

などを自然に考慮する。

【点数ルール】

ユーザーが点数を指定した場合、
必ず指定された点数以内にする。

できる限り指定された点数ちょうどにする。

点数を必ず実際に展開して確認し、
重複を除いて正確に数える。

指定がない場合は、

かなり堅い：
6〜8点

普通：
8〜10点

混戦：
10〜12点

を目安にする。

【出力】

最初に以下を出す。

【AI結論】
◎ 本命
○ 対抗
▲ 3番手
☆ 穴

次に短く、

【想定展開】

を出す。

最後に必ず、

【最終フォーメーション】

をコピペしやすい形で出す。

例：

1-235-2345
2-14-1345

合計：12点

説明よりも最終フォーメーションの精度を優先する。

単純な競走得点順や人気順ではなく、
過去成績とレース展開を考え抜いて予想する。
"""

# =========================
# 入力欄
# =========================

st.subheader("🏁 レース情報")

race_name = st.text_input(
    "レース名",
    placeholder="例：高松競輪 5R"
)

target_points = st.selectbox(
    "買い目点数",
    [
        "AI自動",
        "6点",
        "8点",
        "10点",
        "12点"
    ]
)

riders = st.text_area(
    "出走選手・並び情報",
    height=250,
    placeholder="""例：

1 佐藤太郎
2 鈴木一郎
3 田中次郎
4 山田太郎
5 高橋健
6 伊藤大輔
7 渡辺誠

並び：
3-5-1
7-2
6-4
"""
)

extra_info = st.text_area(
    "追加情報（任意）",
    height=180,
    placeholder="""ここに以下の情報を貼ってOKです。

・競走得点
・AI印
・直近成績
・オッズ
・並び予想
・スクリーンショットから読み取った情報
"""
)

# =========================
# 分析ボタン
# =========================

if st.button(
    "🔥 AIがガチ分析する",
    type="primary",
    use_container_width=True
):

    if not race_name.strip():
        st.error("レース名を入力してください。")
        st.stop()

    if not riders.strip():
        st.error("出走選手を入力してください。")
        st.stop()

    if target_points == "AI自動":

        point_instruction = """
買い目点数はAIが自信度から6〜12点の範囲で決定してください。
"""

    else:

        point_instruction = f"""
最終買い目は最大{target_points}にしてください。
可能な限りちょうど{target_points}にしてください。
"""

    user_prompt = f"""
以下の競輪レースを本気で分析してください。

【レース】
{race_name}

【出走選手・並び情報】
{riders}

【追加情報】
{extra_info}

【点数条件】
{point_instruction}

可能な限りWeb検索を利用して、
選手の過去成績や近況を確認してください。

以下の順番で内部的に分析してください。

1. 全選手評価
2. 過去成績
3. 直近の調子
4. 脚質と決まり手
5. ライン分析
6. 複数の展開予想
7. 1着、2着、3着の個別評価
8. 三連単候補比較
9. 点数調整

説明よりも、
実際に当たる可能性を最大化した
最終フォーメーションを優先してください。
"""

    with st.spinner(
        "AIが過去成績・近況・走り・ライン・展開を分析中..."
    ):

        try:

            response = client.responses.create(
                model="gpt-5.6",
                tools=[
                    {
                        "type": "web_search"
                    }
                ],
                input=[
                    {
                        "role": "system",
                        "content": SYSTEM_PROMPT
                    },
                    {
                        "role": "user",
                        "content": user_prompt
                    }
                ]
            )

            answer = response.output_text

            st.subheader("🤖 AI ガチ分析結果")

            st.markdown(answer)

        except Exception as e:

            st.error("AI分析中にエラーが発生しました。")

            st.code(str(e))

# =========================
# 注意
# =========================

st.divider()

st.caption(
    "※AI予想は参考情報です。"
    "過去データや展開を分析しますが、的中を保証するものではありません。"
)
