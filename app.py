import os
import json
import re
import streamlit as st
from openai import OpenAI

# ==========================================
# 設定
# ==========================================

st.set_page_config(
    page_title="競輪AI ガチ分析版",
    page_icon="🚴",
    layout="wide"
)

st.title("🚴 競輪AI ガチ分析版")
st.caption(
    "AIが選手の過去成績・近況・走り・ライン・展開を調査して"
    "考え抜いたフォーメーションを作成"
)


# ==========================================
# APIキー
# ==========================================

try:
    api_key = st.secrets["OPENAI_API_KEY"]
except Exception:
    api_key = os.getenv("OPENAI_API_KEY")


if not api_key:
    st.error("OPENAI_API_KEY が設定されていません。")
    st.stop()


client = OpenAI(
    api_key=api_key
)


# ==========================================
# AIシステム指示
# ==========================================

SYSTEM_PROMPT = """
あなたは競輪の三連単予想を専門にする、
高度なデータ分析AIです。

あなたの目的は、
単純な競走得点順や人気順の予想ではありません。

Web検索で利用可能な情報と、
ユーザーから与えられたレース情報を総合分析し、
実際に起こる可能性が高いレース展開を考え抜き、
最も実戦的な三連単フォーメーションを作成してください。

======================================
最重要原則
======================================

必ず予想前に可能な限り情報を調査してください。

特に以下を調査・分析してください。

・各選手の直近成績
・直近の着順
・直近レース内容
・競走得点
・勝率
・連対率
・3連対率
・S
・H
・B
・決まり手
・逃げ
・捲り
・差し
・マーク
・脚質
・近況の上昇下降
・選手の走り方
・先行力
・捲り力
・番手戦の強さ
・追込み能力
・ライン構成
・並び予想
・各ラインの長さ
・主導権争い
・先行争い
・過去の対戦
・バンク特性
・開催レベル

情報が見つからない場合は、
存在しないデータを作ってはいけません。

======================================
分析方法
======================================

STEP1
全選手の過去データと近況を分析する。

単純な着順だけでなく、
着順の安定性、
直近の上昇下降、
決まり手、
走り方を分析する。

STEP2
ライン構成を分析する。

誰が先頭か。
誰が番手か。
誰が3番手か。

各ラインの長さを確認する。

STEP3
レース展開を最低3パターン考える。

A：本命ラインが主導権を取る展開
B：別線の自力選手が捲る展開
C：先行争いから番手・追込み選手が浮上する展開

必要ならさらに展開を追加する。

STEP4
1着・2着・3着を別々に評価する。

単純に能力順位を
1着・2着・3着に並べてはいけない。

選手ごとに、

・1着になる確率
・2着になる確率
・3着になる確率
・展開次第の浮上率

を考える。

======================================
フォーメーション作成ルール
======================================

最重要：

1着固定ばかりにしてはいけない。

明確な1強でない限り、
1着候補は原則2人程度。

1着と2着を固定した買い方を
何度も繰り返してはいけない。

悪い例：

1-2-345
1-2-367

これは1-2固定なので禁止。

展開によって自然に、

1が1着で2が2着になる場合
2が1着で1が2着になる場合
別選手が2着に浮上する場合

を考慮する。

======================================
点数
======================================

ユーザーが点数を指定した場合は
必ずその点数以内にする。

指定がない場合は、
AIの自信度で以下の範囲にする。

かなり堅い：
6〜8点

普通：
8〜10点

混戦：
10〜12点

必ず実際の三連単を展開し、
重複を除いた点数を確認する。

======================================
オッズ
======================================

まずオッズを見ない状態で
データと展開から評価する。

その後、
オッズが利用できる場合のみ
期待値確認に使用する。

オッズだけで本命を変更してはいけない。

======================================
出力
======================================

回答は簡潔にする。

最初に、

【AI結論】
◎ 本命
○ 対抗
▲ 3番手
☆ 穴

を出す。

次に、

【想定展開】

を短く出す。

最後に必ず、

【最終フォーメーション】

をコピペしやすい形式で出す。

例：

1-235-2345
2-14-1345

合計：12点

最終フォーメーションは、
実際の展開に基づいた自然な形にする。

単純な能力順の買い目は禁止。

AIは回答前に可能な限り調査し、
過去成績とレース展開を考え抜いてください。
"""


# ==========================================
# 入力
# ==========================================

st.subheader("🏁 レース情報")

col1, col2 = st.columns(2)

with col1:

    race_name = st.text_input(
        "レース名",
        placeholder="例：高松競輪 5R"
    )

with col2:

    target_points = st.selectbox(
        "買い目点数",
        [
            "AI自動",
            "6点",
            "8点",
            "10点",
            "12点"
        ]
    )


riders = st.text_area(
    "出走選手・並び情報",
    height=220,
    placeholder="""
例：

1 佐藤太郎
2 鈴木一郎
3 田中次郎
4 山田太郎
5 高橋健
6 伊藤大輔
7 渡辺誠

並び：
3-5-1
7-2
6-4
"""
)


extra_info = st.text_area(
    "追加情報（任意）",
    height=150,
    placeholder="""
AI印、オッズ、直近成績、
並び予想など、
分かる情報があればここに貼ってください。
"""
)


# ==========================================
# 予想
# ==========================================

if st.button(
    "🔥 AIがガチ分析する",
    type="primary",
    use_container_width=True
):

    if not race_name.strip():
        st.error("レース名を入力してください。")
        st.stop()

    if not riders.strip():
        st.error("出走選手を入力してください。")
        st.stop()


    if target_points == "AI自動":

        point_instruction = """
AIがレースの自信度から
6〜12点の範囲で自動決定してください。
"""

    else:

        point_instruction = f"""
最終買い目は
最大{target_points}にしてください。

可能ならちょうど
{target_points}にしてください。
"""


    user_prompt = f"""
以下の競輪レースを
本気で分析してください。

レース：
{race_name}

出走選手：
{riders}

追加情報：
{extra_info}

点数条件：
{point_instruction}

まず可能な限りWeb検索を利用し、
選手の過去成績や近況を調査してください。

その後、

1. 全選手評価
2. 過去成績分析
3. 直近の調子
4. 脚質と決まり手
5. ライン分析
6. 複数の展開予想
7. 1着・2着・3着の個別評価
8. 三連単候補比較
9. 点数調整

の順で内部分析してください。

最後にユーザーへ、
最も考え抜いたフォーメーションを出してください。

説明よりも、
最終フォーメーションの精度を最優先してください。
"""


    with st.spinner(
        "過去成績・近況・走り方・展開をAIが分析中..."
    ):

        try:

            response = client.responses.create(
                model="gpt-5.6",
                tools=[
                    {
                        "type": "web_search"
                    }
                ],
                input=[
                    {
                        "role": "system",
                        "content": SYSTEM_PROMPT
                    },
                    {
                        "role": "user",
                        "content": user_prompt
                    }
                ]
            )


            answer = response.output_text


            st.subheader("🤖 AI ガチ分析結果")

            st.markdown(answer)


        except Exception as e:

            st.error("AI分析中にエラーが発生しました。")

            st.code(str(e))


# ==========================================
# 注意
# ==========================================

st.divider()

st.caption(
    "※AI予想は参考情報です。"
    "過去データや展開を分析しますが、"
    "的中を保証するものではありません。"
)
