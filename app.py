import os
import streamlit as st
from openai import OpenAI

# ==========================================
# アプリ設定
# ==========================================

st.set_page_config(
    page_title="競輪AI ガチ分析版",
    page_icon="🚴",
    layout="wide"
)

st.title("🚴 競輪AI ガチ分析版")
st.caption(
    "AIが過去成績・近況・脚質・決まり手・ライン・展開を分析し、"
    "考え抜いた三連単フォーメーションを作成します。"
)

# ==========================================
# APIキー取得
# ==========================================

api_key = None

try:
    api_key = st.secrets["OPENAI_API_KEY"]
except Exception:
    api_key = os.getenv("OPENAI_API_KEY")

if not api_key:
    st.error("OPENAI_API_KEY が設定されていません。")
    st.stop()

client = OpenAI(api_key=api_key)

# ==========================================
# AIシステム指示
# ==========================================

SYSTEM_PROMPT = """
あなたは競輪の三連単予想を専門にする、
高度なデータ分析AIです。

目的は単純な競走得点順・人気順の予想ではありません。

ユーザーが指定したレースについて、
利用可能な情報を可能な限り調査・分析し、

・過去成績
・直近成績
・近況の上昇下降
・競走得点
・脚質
・決まり手
・逃げ
・捲り
・差し
・マーク
・先行力
・捲り力
・追込み能力
・ライン構成
・並び
・バンク特性
・主導権争い
・過去対戦
・展開

を総合評価してください。

======================================
重要
======================================

データが見つからない場合、
存在しないデータを作ってはいけません。

分からないことを事実のように断定してはいけません。

ユーザーから与えられた情報と、
利用可能な最新情報を区別してください。

======================================
分析手順
======================================

STEP1
全選手を個別評価する。

単純な競走得点だけではなく、

・近況の安定性
・直近の着順
・走りの内容
・脚質
・決まり手
・ラインでの役割

を分析する。

STEP2
ライン構成を確認する。

誰が自力選手か。
誰が番手か。
誰が3番手か。

各ラインの長さと、
ラインの強さを評価する。

STEP3
レース展開を最低3パターン考える。

A：
本命ラインが主導権を取る展開

B：
別線の自力選手が捲る展開

C：
先行争いになり、
番手・追込み選手が浮上する展開

必要なら追加する。

STEP4
1着・2着・3着を別々に評価する。

単純な能力順位を
1着→2着→3着に並べてはいけない。

選手ごとに、

・1着になる可能性
・2着になる可能性
・3着になる可能性
・展開次第で浮上する可能性

を考える。

======================================
フォーメーション作成ルール
======================================

明確な1強でない限り、
1着候補は原則2人程度を中心にする。

1着と2着を完全固定した買い方を
何度も繰り返してはいけない。

悪い例：

1-2-345
1-2-367

このような、
同じ1着・2着固定の繰り返しは禁止。

展開に応じて自然に、

・1が1着で2が2着
・2が1着で1が2着
・別の選手が2着に浮上
・ラインの3番手が3着
・別線が絡む

という形を考慮する。

変則的すぎるフォーメーションではなく、
実戦で見やすい自然な形にする。

======================================
点数
======================================

ユーザーが点数を指定した場合は、
必ずその指定点数ちょうどにしてください。

最大○点ではなく、
必ずちょうど○点にしてください。

フォーメーションを作成した後、
実際の三連単組み合わせを展開し、

・重複を削除
・点数を再計算

してください。

指定点数と違う場合は、
買い目を修正してから回答してください。

AI自動の場合は、
レースの混戦度に応じて
6点〜20点の範囲で決定してください。

======================================
オッズ
======================================

まずオッズを見ない状態で、
データと展開から予想を組み立てる。

オッズは最後に期待値確認や
買い目の優先順位調整に使う。

オッズだけで本命評価を大きく変えてはいけない。

======================================
出力形式
======================================

最初に簡潔に、

【AI結論】
◎ 本命
○ 対抗
▲ 3番手
☆ 穴

【想定展開】

を出す。

最後に必ず、

【最終フォーメーション】

をコピペしやすい形式で出す。

例：

1-235-2345
2-14-1345

合計：12点

最終フォーメーションは、
実際のレース展開に基づいて作成する。

最終回答では、
必ず指定点数と実際の点数が一致していることを確認する。
"""

# ==========================================
# レース情報入力
# ==========================================

st.divider()

st.subheader("🏁 レース情報")

race_name = st.text_input(
    "レース名",
    placeholder="例：高松競輪 5R"
)

target_points = st.selectbox(
    "買い目点数",
    [
        "AI自動",
        "6点",
        "7点",
        "8点",
        "9点",
        "10点",
        "11点",
        "12点",
        "13点",
        "14点",
        "15点",
        "16点",
        "17点",
        "18点",
        "19点",
        "20点"
    ],
    index=7
)

riders = st.text_area(
    "出走選手・並び情報",
    height=300,
    placeholder="""例：

1 佐藤太郎
2 鈴木一郎
3 田中次郎
4 山田太郎
5 高橋健
6 伊藤大輔
7 渡辺誠

並び：
3-5-1
7-2
6-4"""
)

extra_info = st.text_area(
    "追加情報（任意）",
    height=180,
    placeholder="""AI予想、オッズ、直近成績、
競走得点、並び予想など、
分かる情報があれば貼ってください。"""
)

# ==========================================
# AI分析
# ==========================================

if st.button(
    "🔥 AIがガチ分析する",
    type="primary",
    use_container_width=True
):

    if not race_name.strip():
        st.error("レース名を入力してください。")
        st.stop()

    if not riders.strip():
        st.error("出走選手・並び情報を入力してください。")
        st.stop()

    # ======================================
    # 点数条件
    # ======================================

    if target_points == "AI自動":

        point_instruction = """
買い目点数はAIが自動決定してください。

レースの混戦度と自信度から、
6点〜20点の範囲で決定してください。

最終的に必ず実際の組み合わせを数え、
重複を除いた正確な点数を表示してください。
"""

    else:

        point_count = int(
            target_points.replace("点", "")
        )

        point_instruction = f"""
最終フォーメーションは、
必ずちょうど{point_count}点にしてください。

最大{point_count}点ではありません。

実際の三連単組み合わせを展開して、
重複を除いた点数が
必ずちょうど{point_count}点になることを
確認してください。

点数が{point_count}点にならない場合は、
回答前にフォーメーションを修正してください。

最終回答には、
「合計：{point_count}点」
と表示してください。
"""

    # ======================================
    # AIへ送る内容
    # ======================================

    user_prompt = f"""
以下の競輪レースを本気で分析してください。

======================================
レース
======================================

{race_name}

======================================
出走選手・並び
======================================

{riders}

======================================
追加情報
======================================

{extra_info}

======================================
点数条件
======================================

{point_instruction}

======================================
AIへの指示
======================================

可能な限り利用可能な情報を調査し、

1. 全選手評価
2. 過去成績
3. 直近成績
4. 近況の上昇下降
5. 脚質
6. 決まり手
7. ライン構成
8. バンク特性
9. 複数の展開パターン
10. 1着・2着・3着の個別評価
11. 三連単候補比較
12. 点数調整

を内部で十分に分析してください。

単純な人気順や競走得点順ではなく、
実際に起こりそうな展開を最優先してください。

最終フォーメーションの精度を最優先してください。
"""

    # ======================================
    # OpenAI API実行
    # ======================================

    with st.spinner(
        "AIが過去成績・近況・脚質・ライン・展開を分析中..."
    ):

        try:

            response = client.responses.create(
                model="gpt-5.6",
                tools=[
                    {
                        "type": "web_search"
                    }
                ],
                input=[
                    {
                        "role": "system",
                        "content": SYSTEM_PROMPT
                    },
                    {
                        "role": "user",
                        "content": user_prompt
                    }
                ]
            )

            answer = response.output_text

            st.divider()

            st.subheader("🤖 AI ガチ分析結果")

            st.markdown(answer)

        except Exception as e:

            st.error("AI分析中にエラーが発生しました。")

            st.code(str(e))

# ==========================================
# 注意
# ==========================================

st.divider()

st.caption(
    "※AI予想は参考情報です。"
    "過去データや展開を分析しますが、"
    "的中を保証するものではありません。"
)
